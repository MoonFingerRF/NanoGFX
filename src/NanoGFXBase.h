// ============================================================================
//  NanoGFXBase.h — the Adafruit_GFX subset NanoGFX needs, with no Arduino underneath.
//
//  PackCanvas was written against Adafruit_GFX, and on an Arduino build it still is:
//  this header is only used when Adafruit_GFX is absent (ESP-IDF, ESPHome, a host
//  compiler) or when NANOGFX_STANDALONE is defined. It provides the two classes
//  PackCanvas derives from and calls into — NanoGFX_Base (Adafruit_GFX's drawing,
//  text and font state) and NanoGFX_Canvas8 (GFXcanvas8) — with the same members,
//  the same virtuals and the same pixel output, so every byte-identical claim in
//  PackCanvas.h holds in both builds.
//
//  What is here: pixels, lines, rects, round rects, circles, triangles, 1-bit
//  bitmaps, the classic 5x7 font (PackFont5x7.h, the same table) and GFXfont
//  proportional fonts (the fontconvert format, so existing Adafruit font headers and
//  tools/ttf2gfxfont.py output both work), getTextBounds, print/printf.
//  What is not: Print/String/__FlashStringHelper, ellipses, rotated rects, RGB and
//  grayscale bitmaps, invertDisplay — nothing in NanoGFX uses them.
//
//  The function bodies are Adafruit_GFX 1.12's, renamed and made inline.
//  Copyright (c) 2013 Adafruit Industries. BSD license (see LICENSE-Adafruit-GFX).
// ============================================================================
